"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const path = require("node:path");
const html = fs.readFileSync(path.join(__dirname, "../src/animation.html"), "utf8");
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
let next = 0, paints = 0;
const requests = new Map(), dot = { style: {} }, listeners = {};
const brush = {setTransform(){},clearRect(){},beginPath(){},arc(){},fill(){paints++;}};
const canvas = {style:{},getContext:()=>brush};
const context = vm.createContext({window:{devicePixelRatio:2,addEventListener:(name,callback)=>{listeners[name]=callback;}}, document:{getElementById:id=>id==="dot"?dot:canvas, visibilityState:"visible", hidden:false}, innerWidth:252, innerHeight:22, performance:{now:()=>0}, requestAnimationFrame:cb=>{requests.set(++next,cb);return next;}, cancelAnimationFrame:id=>requests.delete(id)});
vm.runInContext(script, context);
const spark = context.window.spark;
assert.equal(requests.size,0);
spark.start(false);
spark.start(false);
assert.equal(requests.size,1,"starting twice must not create two animation loops");
function step(t){const [id,cb]=requests.entries().next().value;requests.delete(id);cb(t);}
step(100);step(116);
assert.equal(spark.snapshot().callbackCount,2);
assert.match(dot.style.transform,/translateX/);
step(1300);
assert.equal(dot.style.transform,"translateX(246.000px)","original cosine reaches the far edge after half a cycle");
spark.setMethod("canvas");
assert.equal(requests.size,0,"switching methods must cancel the preceding loop");
assert.equal(spark.snapshot().running,false);
assert.equal(canvas.style.display,"block");
assert.equal(dot.style.display,"none");
assert.equal(canvas.width,504,"canvas backing store must follow the device scale");
assert.equal(canvas.height,44);
const beforeCanvas=paints;
spark.start(false);step(2000);step(2016);
assert.equal(paints,beforeCanvas+2,"Canvas mode must actually redraw, not just count callbacks");
assert.equal(spark.snapshot().method,"canvas");
spark.stop();
assert.equal(requests.size,0);
const position=dot.style.transform;
const beforeNoPaint=paints;
spark.start(true);step(132);
assert.equal(dot.style.transform,position,"self-test must not animate pixels");
assert.equal(paints,beforeNoPaint,"self-test must not redraw Canvas pixels");
context.document.visibilityState="hidden";context.document.hidden=true;
assert.equal(spark.snapshot().visibilityState,"hidden");
assert.equal(spark.snapshot().documentHidden,true);
spark.stop();
assert.equal(requests.size,0);
spark.setMethod("ball");
assert.equal(canvas.style.display,"none");
assert.equal(dot.style.display,"block");
assert.throws(()=>spark.setMethod("unknown"));
assert.equal(requests.size,0);
assert(!/\bfetch\s*\(|https?:\/\//i.test(html));
console.log("PASS: original cosine ball; Canvas actually draws; one loop only; switches and Stop cancel it; DPI backing size; no-paint self-test; local content only.");
