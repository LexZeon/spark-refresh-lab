"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const path = require("node:path");
const html = fs.readFileSync(path.join(__dirname, "../src/animation.html"), "utf8");
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
let next = 0;
const requests = new Map(), dot = { style: {} };
const context = vm.createContext({window:{}, document:{getElementById:()=>dot, visibilityState:"visible", hidden:false}, innerWidth:220, performance:{now:()=>0}, requestAnimationFrame:cb=>{requests.set(++next,cb);return next;}, cancelAnimationFrame:id=>requests.delete(id)});
vm.runInContext(script, context);
const spark = context.window.spark;
assert.equal(requests.size,0);
spark.start(false);
function step(t){const [id,cb]=requests.entries().next().value;requests.delete(id);cb(t);}
step(100);step(116);
assert.equal(spark.snapshot().callbackCount,2);
assert.match(dot.style.transform,/translate3d/);
spark.stop();
assert.equal(requests.size,0);
const position=dot.style.transform;
spark.start(true);step(132);
assert.equal(dot.style.transform,position,"self-test must not animate pixels");
context.document.visibilityState="hidden";context.document.hidden=true;
assert.equal(spark.snapshot().visibilityState,"hidden");
assert.equal(spark.snapshot().documentHidden,true);
spark.stop();
assert.equal(requests.size,0);
assert(!/\bfetch\s*\(|https?:\/\//i.test(html));
console.log("PASS: initially stopped; rAF starts/stops; callback count is separate from visibility; self-test has no painted movement; local content only.");
